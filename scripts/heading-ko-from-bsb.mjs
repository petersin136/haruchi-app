export function titleFromBsbEnglish(en) {
  const key = normEn(en);
  const hit = MAP[key];
  if (hit) {
    const chars = [...hit];
    if (chars.length > 14) return chars.slice(0, 14).join("").trim();
    return hit;
  }
  return "본문 단락";
}

/** MAP에 등록 (빌드 중 신규 제목 축적) */
export function rememberTitle(en, ko) {
  const key = normEn(en);
  if (!key || !ko) return;
  MAP[key] = ko;
}

export function allMappedTitles() {
  return { ...MAP };
}
